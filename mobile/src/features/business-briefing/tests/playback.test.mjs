import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const source = fs.readFileSync(new URL("../services/playback.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const calls = [];
let finishStop;
const speech = { speak: (text, callbacks) => calls.push({ text, callbacks }), stop: () => Promise.resolve(), pause: async () => {}, resume: async () => {} };
const exports = {};
vm.runInNewContext(compiled, { exports, require: name => name === "expo-speech" ? speech : name === "react-native" ? { Platform: { OS: "android" } } : { banglaVoices: x => x }, setTimeout, clearTimeout, Error });
const { BriefingPlayer } = exports;
const tick = () => new Promise(resolve => setImmediate(resolve));
const voice = { identifier: "bn", language: "bn-BD" };
const player = new BriefingPlayer();
const progress = [];
const sequence = player.play(["greeting", "report"], voice, 0.9, index => progress.push(index));
await tick(); assert.equal(calls.length, 1);
calls[0].callbacks.onStart(); calls[0].callbacks.onDone();
await tick(); assert.equal(calls[1].text, "report");
calls[1].callbacks.onStart(); calls[1].callbacks.onDone(); await sequence;
assert.deepEqual(progress, [0, 1]);
const cancelled = player.play(["first", "must not play"], voice, 0.9, () => {});
await tick(); await player.stop(); await cancelled;
assert.equal(calls.length, 3);
// Late callbacks from a cancelled session must not finish a newer utterance.
const newer = player.play(["new"], voice, 0.9, () => {});
await tick(); calls[2].callbacks.onDone(); await player.stop(); await newer;
const interrupted = player.play(["interrupted", "must not follow"], voice, 0.9, () => {});
await tick(); const rejection = assert.rejects(interrupted); calls.at(-1).callbacks.onStopped(); await rejection;
assert.equal(calls.length, 5);
speech.stop = () => new Promise(resolve => { finishStop = resolve; });
const stopping = player.stop();
const pending = player.play(["after stop"], voice, 0.9, () => {});
await tick(); assert.equal(calls.length, 5);
finishStop(); await stopping; await tick(); assert.equal(calls.length, 6);
calls[5].callbacks.onDone(); await pending;
console.log("Passed: sequential playback, cancellation, late callbacks, interruptions, and stop/start race.");
